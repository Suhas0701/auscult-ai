import os
import glob
import numpy as np
import librosa
import soundfile as sf

TARGET_SR = 4000
N_SAMPLES = 1024
PROCESSED_DIR = "dsp-ml/data/processed_cycles"
TEST_VEC_DIR = "dsp-ml/test_vectors"
C_HEADER_PATH = "firmware/include/test_vectors.h"

os.makedirs(TEST_VEC_DIR, exist_ok=True)
os.makedirs("firmware/include", exist_ok=True)

def extract_clean_frame(files_list, start_offset_sec=0.2):
    """
    Loads sliced cycles until finding one with >= 1024 samples,
    extracts the 1024-sample window, and peak-normalizes to [-1.0, 1.0].
    """
    for file_path in files_list:
        audio, _ = librosa.load(file_path, sr=TARGET_SR, mono=True)
        start_idx = int(start_offset_sec * TARGET_SR)
        
        if len(audio) >= (start_idx + N_SAMPLES):
            frame = audio[start_idx : start_idx + N_SAMPLES]
            peak = np.max(np.abs(frame))
            if peak > 0.05:
                return (frame / peak).astype(np.float32)
                
    raise RuntimeError("Could not find a valid cycle with sufficient length.")

print("Extracting real physiological frames from sliced ICBHI cycles...")

# 1. Vector 0: Clean Normal Vesicular Breath
normal_files = sorted(glob.glob(os.path.join(PROCESSED_DIR, "*_normal.wav")))
if not normal_files:
    raise FileNotFoundError("No normal cycles found in processed_cycles/. Run 01_slice_icbhi.py first.")
v0_clean = extract_clean_frame(normal_files)

# 2. Vector 1: Pathological Wheeze
wheeze_files = sorted(glob.glob(os.path.join(PROCESSED_DIR, "*_wheeze.wav")))
if not wheeze_files:
    raise FileNotFoundError("No wheeze cycles found in processed_cycles/. Run 01_slice_icbhi.py first.")
v1_wheeze = extract_clean_frame(wheeze_files)

print("Synthesizing controlled failure mode vectors...")

# 3. Vector 2: Fabric Friction (Broadband white noise simulating clothing rubs)
np.random.seed(42)  # Deterministic seed for reproducible testing
v2_friction = np.random.uniform(-0.85, 0.85, N_SAMPLES).astype(np.float32)

# 4. Vector 3: 50 Hz Mains Hum + 25 Hz Baseline Wobble (Acoustic air-gap / ground loop)
t = np.linspace(0, N_SAMPLES / TARGET_SR, N_SAMPLES, endpoint=False)
v3_hum = (0.75 * np.sin(2 * np.pi * 50 * t) + 0.25 * np.sin(2 * np.pi * 25 * t)).astype(np.float32)

# 5. Vector 4: High-Frequency Ambient Bleed (Speech chatter above 1200 Hz)
v4_speech = (0.60 * np.sin(2 * np.pi * 1500 * t) + 0.40 * np.sin(2 * np.pi * 1850 * t)).astype(np.float32)

vectors = {
    "vector_0_clean": v0_clean,
    "vector_1_wheeze": v1_wheeze,
    "vector_2_friction": v2_friction,
    "vector_3_hum": v3_hum,
    "vector_4_speech": v4_speech
}

# Save individual WAV files for desktop validation and bench audio playback
for name, samples in vectors.items():
    wav_path = os.path.join(TEST_VEC_DIR, f"{name}.wav")
    sf.write(wav_path, samples, TARGET_SR)

# Export standard C header for Track B ESP32 firmware
with open(C_HEADER_PATH, "w") as f:
    f.write("// =============================================================================\n")
    f.write("// AUSCULT-AI: Standardized Gating Test Vectors (Track C Golden Reference)\n")
    f.write("// Auto-generated by dsp-ml/desktop_dsp/02_build_test_vectors.py\n")
    f.write(f"// Sampling Rate: {TARGET_SR} Hz | Frame Length: {N_SAMPLES} samples ({int(N_SAMPLES*1000/TARGET_SR)} ms)\n")
    f.write("// =============================================================================\n\n")
    f.write("#ifndef TEST_VECTORS_H\n")
    f.write("#define TEST_VECTORS_H\n\n")
    f.write(f"#define FRAME_LEN {N_SAMPLES}\n")
    f.write(f"#define SAMPLE_RATE {TARGET_SR}\n\n")
    
    for name, samples in vectors.items():
        arr_str = ", ".join([f"{x:.6f}f" for x in samples])
        f.write(f"// {name}: 1024 float samples normalized in [-1.0, 1.0]\n")
        f.write(f"const float {name}[{N_SAMPLES}] = {{\n  {arr_str}\n}};\n\n")
        
    f.write("#endif // TEST_VECTORS_H\n")

print(f"Generated 5 WAV test vectors in: {TEST_VEC_DIR}/")
print(f"Exported firmware C header to:   {C_HEADER_PATH}")
